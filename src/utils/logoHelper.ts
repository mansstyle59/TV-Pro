export function getSlugsForName(name: string): string[] {
  if (!name) return [];
  let base = name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "") // Supprime les accents
    .toLowerCase()
    .replace(/\b(fr|be|ch|ca|vip|ts|m3u8|tnt|raw|hd|fhd|uhd|4k|sd|raw|backup|s1|s2|s3|hevc)\s*[:|-]\s*/gi, "") // Supprime les préfixes FR:, BE:, etc.
    .replace(/\s*[\[\(](HD|SD|V2|Backup|FR|MULT|7\/24|Main|24\/7|HEVC|480p|1080p|720p|4K|AUTO|OLD|TS|M3U8|VIP|6|7|1080|720|h265)[\]\)]/gi, "")
    .replace(/\s+\([^)]*\)/g, "") // Supprime les parenthèses
    .replace(/\s+\[[^\]]*\]/g, "") // Supprime les crochets
    .replace(/\b(fhd|hd|sd|4k|french|tnt|hevc|1080p|720p|surround|h265)\b/gi, " ");

  const slugs = new Set<string>();

  // Variation 1: Replace '+' with '-plus' which is a common tv-logo pattern (e.g. canal-plus)
  let s1 = base.replace(/\+/g, " plus ").replace(/[^a-z0-9]/g, " ").trim().replace(/\s+/g, "-");
  if (s1) slugs.add(s1);

  // Variation 2: Just strip '+' (e.g. canal) or keep them attached
  let s2 = base.replace(/\+/g, "").replace(/[^a-z0-9]/g, " ").trim().replace(/\s+/g, "-");
  if (s2) slugs.add(s2);
  
  // Clean trailing "france" if someone types "TF1 France" -> TF1
  for (const s of Array.from(slugs)) {
     if (s.endsWith("-france") && s !== "france") {
         slugs.add(s.replace(/-france$/, ""));
     }
  }

  return Array.from(slugs);
}

export function getLogosForChannel(channelName: string, originalLogo?: string): string[] {
  const norm = normalizeName(channelName);
  const urls: string[] = [];

  // 0. Custom user-saved logos
  const customLogos = getCustomLogos();
  if (customLogos[norm]) {
    urls.push(customLogos[norm]);
  }

  // 1. Direct hit in fallbackLogoMap
  if (fallbackLogoMap[norm]) {
    urls.push(fallbackLogoMap[norm]);
  } else {
    // 2. Specific French TNT Fallbacks - sorted by length descending so specific matches take precedence!
    const keys = Object.keys(fallbackLogoMap).sort((a, b) => b.length - a.length);
    for (const k of keys) {
      if (k.length > 3 && (norm.includes(k) || k.includes(norm))) {
        urls.push(fallbackLogoMap[k]);
        break; // Only push the best match
      }
    }
  }

  // 3. Cleaned Original Logo
  if (originalLogo && originalLogo.trim() !== "" && !originalLogo.includes("placeholder")) {
    let cleanLogo = originalLogo.trim();
    if (cleanLogo.includes("iptv-org") && (cleanLogo.includes("/images/channels/") || cleanLogo.includes("/images/logos/") || cleanLogo.includes("/logos/logos/"))) {
      const parts = cleanLogo.split("/");
      const filename = parts[parts.length - 1];
      const baseFilename = filename.toLowerCase().replace(/\.fr\.png$/, "").replace(/\.png$/, "").replace(/[^a-z0-9]/g, "");
      if (fallbackLogoMap[baseFilename]) {
        urls.push(fallbackLogoMap[baseFilename]);
      } else {
        urls.push(`https://raw.githubusercontent.com/tv-logos/tv-logos/main/countries/france/${baseFilename}-fr.png`);
      }
    } else {
      urls.push(cleanLogo);
    }
  }

  // 4. Dynamic Logo Detection based on tv-logos repository conventions
  const slugs = getSlugsForName(channelName);
  for (const slug of slugs) {
    const isBelgian = /rtl|rtbf|laune|tipik|latrois|ab3|abxplore|ln24|be\b/i.test(channelName) || norm.endsWith("be");
    if (isBelgian) {
      urls.push(`https://raw.githubusercontent.com/tv-logo/tv-logos/main/countries/belgium/${slug}-be.png`);
      urls.push(`https://raw.githubusercontent.com/tv-logos/tv-logos/main/countries/belgium/${slug}-be.png`);
      urls.push(`https://raw.githubusercontent.com/tv-logo/tv-logos/main/countries/belgium/${slug}.png`);
      urls.push(`https://raw.githubusercontent.com/tv-logos/tv-logos/main/countries/belgium/${slug}.png`);
    } else {
      urls.push(`https://raw.githubusercontent.com/tv-logo/tv-logos/main/countries/france/${slug}-fr.png`);
      urls.push(`https://raw.githubusercontent.com/tv-logos/tv-logos/main/countries/france/${slug}-fr.png`);
      urls.push(`https://raw.githubusercontent.com/tv-logo/tv-logos/main/countries/france/${slug}.png`);
      urls.push(`https://raw.githubusercontent.com/tv-logos/tv-logos/main/countries/france/${slug}.png`);
      urls.push(`https://raw.githubusercontent.com/tv-logo/tv-logos/main/countries/france/${slug}-france.png`);
      urls.push(`https://raw.githubusercontent.com/tv-logos/tv-logos/main/countries/france/${slug}-france.png`);
    }
  }

  // Remove duplicates
  return Array.from(new Set(urls));
}

export function getLogoForChannel(channelName: string, originalLogo?: string): string | undefined {
  const logos = getLogosForChannel(channelName, originalLogo);
  return logos.length > 0 ? logos[0] : undefined;
}

export function normalizeName(name: string): string {
  if (!name) return "";
  let n = name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "") // Supprime les accents
    .toLowerCase()
    .replace(/\b(fr|be|ch|ca|vip|ts|m3u8|tnt|raw|hd|fhd|uhd|4k|sd|raw|backup|s1|s2|s3)\s*[:|-]\s*/gi, "") // Supprime les préfixes FR:, BE:, VIP: etc
    .replace(/\s*[\[\(](HD|SD|V2|Backup|FR|MULT|7\/24|Main|24\/7|HEVC|480p|1080p|720p|4K|AUTO|OLD|TS|M3U8|VIP|6|7)[\]\)]/gi, "")
    .replace(/\s+\([^)]*\)/g, "") // Supprime les parenthèses (x) et leur contenu
    .replace(/\s+\[[^\]]*\]/g, "") // Supprime les crochets [x] et leur contenu
    .replace(/\s+fhd\s*/gi, "")
    .replace(/\s+hd\s*/gi, "")
    .replace(/\s+sd\s*/gi, "")
    .replace(/\s+4k\s*/gi, "")
    .replace(/\s*:\s*/g, "")
    .replace(/\s*-+\s*/g, "")
    .replace(/\.(fr|be)\s*$/i, "") // Supprime le suffixe d'extension de nom
    .replace(/\s+/g, "") // Enlève les espaces restants
    .replace(/[^a-z0-9+]/g, ""); // Ne garde que lettres, chiffres, et '+' et '-'

  // Map Canal+ notation variations to avoid '+' and word variation mismatches
  n = n.replace(/\+/g, "plus");

  // Apply alias
  if (CHANNEL_ALIASES[n]) {
    n = CHANNEL_ALIASES[n];
  }

  return n;
}

export function getCustomNames(): Record<string, string> {
  try {
    if (typeof window !== "undefined") {
      const customNamesString = localStorage.getItem("custom_channel_names");
      return customNamesString ? JSON.parse(customNamesString) : {};
    }
  } catch (e) {
    console.error("Error reading custom_channel_names", e);
  }
  return {};
}

export function saveCustomName(channelIdOrNorm: string, newName: string): void {
  try {
    if (typeof window !== "undefined") {
      const customNames = getCustomNames();
      if (newName.trim()) {
        customNames[channelIdOrNorm] = newName.trim();
      } else {
        delete customNames[channelIdOrNorm];
      }
      localStorage.setItem("custom_channel_names", JSON.stringify(customNames));
      window.dispatchEvent(new Event("custom_name_updated"));
    }
  } catch (e) {
    console.error("Error saving custom name", e);
  }
}

